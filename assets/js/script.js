// Sort text in an array alphabetically.
const woorden = ["peer", "appel", "banaan"];
woorden.sort();

console.log(woorden); // ["appel", "banaan", "peer"]

// Example 2: Sort names alphabetically.
const namen = ["Zoe", "Milan", "Anna"];
namen.sort();
console.log(namen); // ["Anna", "Milan", "Zoe"]

// Example 3: Sort words in reverse alphabetical order.
const dieren = ["hond", "aap", "kat"];
dieren.sort().reverse();
console.log(dieren); // ["hond", "kat", "aap"]

